"""Shared catalog logic for datasets AND notebooks.

Source of truth = the per-item metadata.yaml files under
datasets/<slug>/metadata/ and notebooks/<slug>/metadata/.
The index files (DATASETS.md, datasets.json, NOTEBOOKS.md, notebooks.json) and
every per-item README.md are ALWAYS generated from those; never hand-edit them.
"""
