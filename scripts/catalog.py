def dataset_readme_path(slug: str) -> Path:
    return DATASETS_DIR / slug / "README.md"


def notebook_readme_path(slug: str) -> Path:
    return NOTEBOOKS_DIR / slug / "README.md"


def agent_readme_path(slug: str) -> Path:
    return AGENTS_DIR / slug / "README.md"


def build_datasets(validate: bool = True) -> list[dict]:
    records = load_all(validate=validate)
    DATASETS_MD.write_text(render_markdown(records))
    DATASETS_JSON.write_text(render_json(records))
    for r in records:
        dataset_readme_path(r["slug"]).write_text(render_readme(r))
    return records


def build_notebooks(validate: bool = True) -> list[dict]:
    records = load_notebooks(validate=validate)
    NOTEBOOKS_MD.write_text(render_notebooks_markdown(records))
    NOTEBOOKS_JSON.write_text(render_notebooks_json(records))
    for r in records:
        notebook_readme_path(r["slug"]).write_text(render_notebook_readme(r))
    return records


def build_agents(validate: bool, nb_index: dict) -> list[dict]:
    records = load_agents(validate=validate)
    AGENTS_MD.write_text(render_agents_markdown(records, nb_index))
    AGENTS_JSON.write_text(render_agents_json(records, nb_index))
    for r in records:
        agent_readme_path(r["slug"]).write_text(render_agent_readme(r, nb_index))
    return records


def build(validate: bool = True) -> dict[str, list[dict]]:
    """Regenerate every index and README that has a source folder. Returns all lists."""
    out = {"datasets": [], "notebooks": [], "agents": []}
    if DATASETS_DIR.exists():
        out["datasets"] = build_datasets(validate=validate)
    if NOTEBOOKS_DIR.exists():
        out["notebooks"] = build_notebooks(validate=validate)
    if AGENTS_DIR.exists():
        # Agents may link a notebook for their Open-in-Colab; resolve from notebooks.
        nbs = out["notebooks"] or load_notebooks(validate=False)
        out["agents"] = build_agents(validate, nb_colab_index(nbs))
    return out


def check_in_sync() -> list[str]:
    """Return drift problems across datasets and notebooks. Empty == in sync."""
    problems: list[str] = []

    if DATASETS_DIR.exists():
        records = load_all(validate=True)
        if not DATASETS_MD.exists() or DATASETS_MD.read_text() != render_markdown(records):
            problems.append("DATASETS.md is out of sync - run scripts/build_catalog.py")
        if not DATASETS_JSON.exists() or DATASETS_JSON.read_text() != render_json(records):
            problems.append("datasets.json is out of sync - run scripts/build_catalog.py")
        for r in records:
            p = dataset_readme_path(r["slug"])
            if not p.exists() or p.read_text() != render_readme(r):
                problems.append(f"datasets/{r['slug']}/README.md is out of sync "
                                "- run scripts/build_catalog.py")

    if NOTEBOOKS_DIR.exists():
        records = load_notebooks(validate=True)
        if not NOTEBOOKS_MD.exists() or NOTEBOOKS_MD.read_text() != render_notebooks_markdown(records):
            problems.append("NOTEBOOKS.md is out of sync - run scripts/build_catalog.py")
        if not NOTEBOOKS_JSON.exists() or NOTEBOOKS_JSON.read_text() != render_notebooks_json(records):
            problems.append("notebooks.json is out of sync - run scripts/build_catalog.py")
        for r in records:
            p = notebook_readme_path(r["slug"])
            if not p.exists() or p.read_text() != render_notebook_readme(r):
                problems.append(f"notebooks/{r['slug']}/README.md is out of sync "
                                "- run scripts/build_catalog.py")

    if AGENTS_DIR.exists():
        nb_index = nb_colab_index(load_notebooks(validate=False))
        records = load_agents(validate=True)
        if not AGENTS_MD.exists() or AGENTS_MD.read_text() != render_agents_markdown(records, nb_index):
            problems.append("AGENTS.md is out of sync - run scripts/build_catalog.py")
        if not AGENTS_JSON.exists() or AGENTS_JSON.read_text() != render_agents_json(records, nb_index):
            problems.append("agents.json is out of sync - run scripts/build_catalog.py")
        for r in records:
            p = agent_readme_path(r["slug"])
            if not p.exists() or p.read_text() != render_agent_readme(r, nb_index):
                problems.append(f"agents/{r['slug']}/README.md is out of sync "
                                "- run scripts/build_catalog.py")

    return problems
