"""Shared catalog logic: discover metadata, validate it, and generate the
catalog indexes (DATASETS.md for humans, datasets.json for the client).

Source of truth = the per-dataset metadata.yaml files under datasets/<slug>/metadata/.
DATASETS.md and datasets.json are ALWAYS generated from those; never hand-edit them.
"""
from __future__ import annotations

import json
from datetime import date
from pathlib import Path

import yaml
from jsonschema import Draft7Validator

REPO_ROOT = Path(__file__).resolve().parent.parent
DATASETS_DIR = REPO_ROOT / "datasets"
SCHEMA_PATH = REPO_ROOT / "schema" / "metadata.schema.json"
DATASETS_MD = REPO_ROOT / "DATASETS.md"
DATASETS_JSON = REPO_ROOT / "datasets.json"

# Repo coordinates used to build raw-download links in generated READMEs.
OWNER = "CrashingGuru"
REPO = "Sandbox_Training"
BRANCH = "main"
RAW_BASE = f"https://raw.githubusercontent.com/{OWNER}/{REPO}/{BRANCH}"

MD_HEADER = "<!-- AUTO-GENERATED by scripts/build_catalog.py - do not edit by hand -->\n"


def load_schema() -> Draft7Validator:
    with SCHEMA_PATH.open() as fh:
        return Draft7Validator(json.load(fh))


def metadata_paths() -> list[Path]:
    """Every datasets/<slug>/metadata/metadata.yaml, sorted."""
    if not DATASETS_DIR.exists():
        return []
    return sorted(DATASETS_DIR.glob("*/metadata/metadata.yaml"))


def load_all(validate: bool = True) -> list[dict]:
    """Load, (optionally) validate, and return all dataset metadata records.

    Raises ValueError with all problems collected, so one bad file does not
    hide the others.
    """
    validator = load_schema() if validate else None
    records: list[dict] = []
    problems: list[str] = []

    for path in metadata_paths():
        slug_from_dir = path.parent.parent.name
        with path.open() as fh:
            data = yaml.safe_load(fh)

        if validator is not None:
            for err in sorted(validator.iter_errors(data), key=lambda e: e.path):
                loc = "/".join(str(p) for p in err.path) or "(root)"
                problems.append(f"{path.relative_to(REPO_ROOT)} [{loc}]: {err.message}")

        if isinstance(data, dict) and data.get("slug") != slug_from_dir:
            problems.append(
                f"{path.relative_to(REPO_ROOT)}: slug '{data.get('slug')}' "
                f"does not match folder name '{slug_from_dir}'"
            )
        records.append(data)

    if problems:
        raise ValueError("Metadata validation failed:\n  - " + "\n  - ".join(problems))

    records.sort(key=lambda r: r["name"].lower())
    return records


def _md_escape(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def render_markdown(records: list[dict]) -> str:
    lines = [
        MD_HEADER,
        "# Dataset Catalog\n",
        f"_{len(records)} dataset(s). Generated {date.today().isoformat()}._\n",
        "| Name | Slug | Tags | Rows | Added | Metadata |",
        "|------|------|------|------|-------|----------|",
    ]
    for r in records:
        rows = sum(f.get("rows", 0) for f in r["files"]) or ""
        tags = ", ".join(r.get("tags", []))
        meta_link = f"datasets/{r['slug']}/metadata/metadata.yaml"
        lines.append(
            f"| {_md_escape(r['name'])} | `{r['slug']}` | {_md_escape(tags)} "
            f"| {rows} | {r['date_added']} | [link]({meta_link}) |"
        )
    return "\n".join(lines) + "\n"


def render_json(records: list[dict]) -> str:
    """Client-facing index. Kept small and stable; full detail stays in metadata.yaml."""
    out = {
        "generated": date.today().isoformat(),
        "count": len(records),
        "datasets": [
            {
                "slug": r["slug"],
                "name": r["name"],
                "description": r["description"],
                "version": r["version"],
                "tags": r.get("tags", []),
                "date_added": r["date_added"],
                "license": r["license"],
                "source": r.get("source"),
                "files": [
                    {
                        "name": f["path"].split("/")[-1],
                        "path": f"datasets/{r['slug']}/{f['path']}",
                        "rows": f.get("rows"),
                        "columns": f.get("columns"),
                        "bytes": f.get("bytes"),
                        "lfs": f.get("lfs", False),
                    }
                    for f in r["files"]
                ],
                "readme_path": f"datasets/{r['slug']}/README.md",
                "metadata_path": f"datasets/{r['slug']}/metadata/metadata.yaml",
            }
            for r in records
        ],
    }
    return json.dumps(out, indent=2) + "\n"


def _fmt_bytes(n: int | None) -> str:
    if not n:
        return ""
    units = ["B", "KB", "MB", "GB", "TB"]
    size = float(n)
    i = 0
    while size >= 1024 and i < len(units) - 1:
        size /= 1024
        i += 1
    return f"{size:.1f} {units[i]}" if i else f"{int(size)} {units[i]}"


def render_readme(r: dict) -> str:
    """Per-dataset README.md, generated from its metadata."""
    slug = r["slug"]
    lines = [
        MD_HEADER,
        f"# {r['name']}\n",
        f"{r['description']}\n",
        "## Overview\n",
        "| Field | Value |",
        "|-------|-------|",
        f"| Slug | `{slug}` |",
        f"| Version | {r['version']} |",
        f"| License | {r['license']} |",
        f"| Added | {r['date_added']}"
        + (f" by {r['added_by']}" if r.get("added_by") else "") + " |",
    ]
    if r.get("source"):
        lines.append(f"| Source | {r['source']} |")
    if r.get("tags"):
        lines.append(f"| Tags | {', '.join(r['tags'])} |")
    lines.append("")

    lines += ["## Files\n", "| File | Rows | Columns | Size | Storage | Download |",
              "|------|------|---------|------|---------|----------|"]
    for f in r["files"]:
        fname = f["path"].split("/")[-1]
        raw = f"{RAW_BASE}/datasets/{slug}/{f['path']}"
        storage = "Git LFS" if f.get("lfs") else "git"
        lines.append(
            f"| `{fname}` | {f.get('rows', '') or ''} | {f.get('columns', '') or ''} "
            f"| {_fmt_bytes(f.get('bytes'))} | {storage} | [raw]({raw}) |"
        )
    lines.append("")

    # A ready-to-run load snippet for the first tabular file, if any.
    tabular = next((f for f in r["files"]
                    if f["path"].lower().endswith((".csv", ".tsv"))), None)
    if tabular:
        raw = f"{RAW_BASE}/datasets/{slug}/{tabular['path']}"
        sep = r'"\t"' if tabular["path"].lower().endswith(".tsv") else '","'
        lines += [
            "## Load it\n",
            "```python",
            "import pandas as pd",
            f'df = pd.read_csv("{raw}"' + ("" if sep == '","' else f", sep={sep}") + ")",
            "print(df.shape)",
            "df.head()",
            "```\n",
        ]

    lines += [
        "## Integrity\n",
        "SHA-256 checksums for each file are recorded in "
        f"[`metadata/metadata.yaml`](metadata/metadata.yaml).\n",
        "---\n",
        "_This README is generated from `metadata/metadata.yaml`. "
        "Do not edit by hand; run `scripts/build_catalog.py`._\n",
    ]
    return "\n".join(lines)


def readme_path(slug: str) -> Path:
    return DATASETS_DIR / slug / "README.md"


def build(validate: bool = True) -> list[dict]:
    """Regenerate DATASETS.md, datasets.json and every per-dataset README.

    Returns the records.
    """
    records = load_all(validate=validate)
    DATASETS_MD.write_text(render_markdown(records))
    DATASETS_JSON.write_text(render_json(records))
    for r in records:
        readme_path(r["slug"]).write_text(render_readme(r))
    return records


def check_in_sync() -> list[str]:
    """Return a list of drift problems: files that differ from what metadata implies.

    Used by CI to enforce 'generated, not hand-edited'. Empty list == in sync.
    """
    records = load_all(validate=True)
    problems = []
    expected_md = render_markdown(records)
    expected_json = render_json(records)
    if not DATASETS_MD.exists() or DATASETS_MD.read_text() != expected_md:
        problems.append("DATASETS.md is out of sync - run scripts/build_catalog.py")
    if not DATASETS_JSON.exists() or DATASETS_JSON.read_text() != expected_json:
        problems.append("datasets.json is out of sync - run scripts/build_catalog.py")
    for r in records:
        p = readme_path(r["slug"])
        if not p.exists() or p.read_text() != render_readme(r):
            problems.append(
                f"datasets/{r['slug']}/README.md is out of sync - "
                "run scripts/build_catalog.py"
            )
    return problems
