def notebook_file(r: dict) -> dict:
    """The primary .ipynb file record, else the first file."""
    return next((f for f in r["files"] if f["path"].lower().endswith(".ipynb")),
                r["files"][0])


def colab_url(r: dict) -> str:
    return f"{COLAB_BASE}/notebooks/{r['slug']}/{notebook_file(r)['path']}"


def render_notebooks_markdown(records: list[dict]) -> str:
    lines = [
        MD_HEADER,
        "# Notebook Catalog\n",
        f"_{len(records)} notebook(s). Generated {date.today().isoformat()}._\n",
        "| Name | Slug | Dataset | Language | Added | Open in Colab | Metadata |",
        "|------|------|---------|----------|-------|---------------|----------|",
    ]
    for r in records:
        ds = r.get("dataset") or ""
        ds_cell = f"[`{ds}`](datasets/{ds}/README.md)" if ds else ""
        meta_link = f"notebooks/{r['slug']}/metadata/metadata.yaml"
        colab = f"[![Open In Colab]({COLAB_BADGE})]({colab_url(r)})"
        lines.append(
            f"| {_md_escape(r['name'])} | `{r['slug']}` | {ds_cell} "
            f"| {_md_escape(r.get('language', ''))} | {r['date_added']} "
            f"| {colab} | [link]({meta_link}) |"
        )
    return "\n".join(lines) + "\n"


