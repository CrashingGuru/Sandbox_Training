# --------------------------------------------------------------------------- #
# Loading & validation (shared)
# --------------------------------------------------------------------------- #
def _validator(schema_path: Path) -> Draft7Validator:
    with schema_path.open() as fh:
        return Draft7Validator(json.load(fh))


def _load_records(base_dir: Path, schema_path: Path, validate: bool) -> list[dict]:
    """Load, (optionally) validate and return all metadata records under base_dir.

    Collects every problem so one bad file does not hide the others.
    """
    validator = _validator(schema_path) if validate else None
    records: list[dict] = []
    problems: list[str] = []

    for path in sorted(base_dir.glob("*/metadata/metadata.yaml")):
        slug_from_dir = path.parent.parent.name
        with path.open() as fh:
            data = yaml.safe_load(fh)

        if validator is not None:
            for err in sorted(validator.iter_errors(data), key=lambda e: list(e.path)):
                loc = "/".join(str(p) for p in err.path) or "(root)"
                problems.append(f"{path.relative_to(REPO_ROOT)} [{loc}]: {err.message}")

        if isinstance(data, dict) and data.get("slug") != slug_from_dir:
            problems.append(
                f"{path.relative_to(REPO_ROOT)}: slug '{data.get('slug')}' "
                f"does not match folder name '{slug_from_dir}'"
            )
        records.append(data)

    if problems:
        raise ValueError("Metadata validation failed:\n  - " + "\n  - ".join(problems))

    records.sort(key=lambda r: r["name"].lower())
    return records


def load_all(validate: bool = True) -> list[dict]:
    return _load_records(DATASETS_DIR, DATASET_SCHEMA_PATH, validate)


def load_notebooks(validate: bool = True) -> list[dict]:
    return _load_records(NOTEBOOKS_DIR, NOTEBOOK_SCHEMA_PATH, validate)


def load_agents(validate: bool = True) -> list[dict]:
    return _load_records(AGENTS_DIR, AGENT_SCHEMA_PATH, validate)


# --------------------------------------------------------------------------- #
# Formatting helpers (shared)
# --------------------------------------------------------------------------- #
def _md_escape(text) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def _fmt_bytes(n: int | None) -> str:
    if not n:
        return ""
    units = ["B", "KB", "MB", "GB", "TB"]
    size = float(n)
    i = 0
    while size >= 1024 and i < len(units) - 1:
        size /= 1024
        i += 1
    return f"{size:.1f} {units[i]}" if i else f"{int(size)} {units[i]}"


